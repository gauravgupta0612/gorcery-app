// Firebase Cloud Messaging is enabled only when app/google-services.json is present.
val hasFirebaseConfig = file("google-services.json").exists()
if (hasFirebaseConfig) apply(plugin = "com.google.gms.google-services")

// Release signing is read from keystore.properties (never commit it). See documentation/ANDROID_BUILD.md.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

val apiBaseUrl: String = (project.findProperty("golaApiBaseUrl") as String?) ?: "http://10.0.2.2:8095/"

