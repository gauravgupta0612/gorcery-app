#!/usr/bin/env python3
"""Generates database/migrations/V2__seed_catalog.sql and placeholder product
artwork in database/seed-images/ from catalog_data.py.

Usage:  python3 generate_seed.py            (from database/scripts)
Images are branded placeholder tiles - replace with real product photography
through the admin dashboard (Products -> Images -> Upload).
"""
import os, re, sys, random
from decimal import Decimal
from catalog_data import CATEGORIES, BANNERS, COUPONS, PINCODES

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT_SQL = os.path.join(ROOT, "migrations", "V2__seed_catalog.sql")
IMG_DIR = os.path.join(ROOT, "seed-images")
random.seed(42)

def slugify(s):
    s = s.lower().replace("&", "and").replace("'", "")
    return re.sub(r"[^a-z0-9]+", "-", s).strip("-")

def q(s):
    return "NULL" if s is None else "'" + str(s).replace("'", "''") + "'"

def ean13(n):
    base = f"890{n:09d}"
    total = sum(int(d) * (3 if i % 2 else 1) for i, d in enumerate(base))
    return base + str((10 - total % 10) % 10)

def make_images(slug, title, brand, color, label):
    try:
        from PIL import Image, ImageDraw, ImageFont
    except ImportError:
        return
    os.makedirs(IMG_DIR, exist_ok=True)
    fb = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
    fr = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
    c = tuple(int(color[i:i+2], 16) for i in (1, 3, 5))
    for idx in (1, 2):
        W = 600
        img = Image.new("RGB", (W, W), (255, 255, 255))
        d = ImageDraw.Draw(img)
        # soft tinted background
        tint = tuple(int(255 - (255 - ch) * 0.12) for ch in c)
        d.rounded_rectangle([20, 20, W - 20, W - 20], 48, fill=tint)
        if idx == 1:
            d.ellipse([170, 90, 430, 350], fill=c)
            initials = "".join(w[0] for w in re.findall(r"[A-Za-z]+", title)[:2]).upper()
            f = ImageFont.truetype(fb, 110)
            tw = d.textlength(initials, font=f)
            d.text(((W - tw) / 2, 150), initials, font=f, fill=(255, 255, 255))
            y = 385
        else:
            d.rectangle([20, 70, W - 20, 150], fill=c)
            f = ImageFont.truetype(fb, 40)
            t = brand.upper()[:22]
            d.text(((W - d.textlength(t, font=f)) / 2, 88), t, font=f, fill=(255, 255, 255))
            y = 230
        f = ImageFont.truetype(fb, 34)
        words, lines, cur = title.split(), [], ""
        for w in words:
            if d.textlength((cur + " " + w).strip(), font=f) > W - 100:
                lines.append(cur); cur = w
            else:
                cur = (cur + " " + w).strip()
        lines.append(cur)
        for ln in lines[:3]:
            d.text(((W - d.textlength(ln, font=f)) / 2, y), ln, font=f, fill=(33, 33, 33)); y += 44
        f2 = ImageFont.truetype(fr, 28)
        sub = label if idx == 1 else "Gola Grocery · Quality checked"
        d.text(((W - d.textlength(sub, font=f2)) / 2, y + 12), sub, font=f2, fill=(90, 90, 90))
        img.save(os.path.join(IMG_DIR, f"{slug}-{idx}.png"), optimize=True)

def make_banner(slug, title, subtitle, color):
    try:
        from PIL import Image, ImageDraw, ImageFont
    except ImportError:
        return
    c = tuple(int(color[i:i+2], 16) for i in (1, 3, 5))
    img = Image.new("RGB", (1200, 500), c)
    d = ImageDraw.Draw(img)
    for i in range(6):
        r = 120 + i * 60
        d.ellipse([1050 - r, 250 - r, 1050 + r, 250 + r], outline=(255, 214, 0), width=3)
    fb = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 64)
    fr = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 36)
    d.text((70, 150), title, font=fb, fill=(255, 255, 255))
    d.text((70, 250), subtitle, font=fr, fill=(255, 241, 118))
    d.rounded_rectangle([70, 330, 330, 400], 30, fill=(255, 214, 0))
    d.text((110, 343), "Shop now", font=fr, fill=(27, 94, 32))
    os.makedirs(IMG_DIR, exist_ok=True)
    img.save(os.path.join(IMG_DIR, f"banner-{slug}.png"), optimize=True)

def main(with_images=True):
    out = ["-- AUTO-GENERATED by database/scripts/generate_seed.py - do not edit by hand.",
           "-- Sample catalogue: illustrative prices in INR; synthetic EAN-13 barcodes.", ""]
    brands = sorted({p[1] for _, _, _, _, subs in CATEGORIES for _, _, prods in subs for p in prods})
    out.append("INSERT INTO brands(name) VALUES " + ",\n  ".join(f"({q(b)})" for b in brands) + ";\n")
    out.append("INSERT INTO suppliers(name, contact_name, phone, email, gstin, address) VALUES\n"
               "  ('Fresh Farms Agro Pvt Ltd', 'Ramesh Kumar', '9810000001', 'orders@freshfarms.example', '09AAACF1234A1Z5', 'Azadpur Mandi, Delhi'),\n"
               "  ('National FMCG Distributors', 'Sunita Sharma', '9810000002', 'sales@nfd.example', '09AAACN5678B1Z2', 'Sector 63, Noida'),\n"
               "  ('Kirana Wholesale Traders', 'Mohd. Irfan', '9810000003', 'kwt@wholesale.example', '07AAACK9012C1Z9', 'Khari Baoli, Delhi');\n")
    sku_n = 0
    for ci, (code, cname, cname_hi, color, subs) in enumerate(CATEGORIES):
        cslug = slugify(cname)
        out.append(f"-- {cname}")
        out.append(f"INSERT INTO categories(parent_id, name, name_hi, slug, image_url, sort_order) VALUES "
                   f"(NULL, {q(cname)}, {q(cname_hi)}, {q(cslug)}, {q('/files/catalog/category-' + cslug + '-1.png')}, {ci});")
        if with_images:
            make_images("category-" + cslug, cname, "Gola Grocery", color, cname_hi and "")
        for si, (sname, sname_hi, prods) in enumerate(subs):
            sslug = cslug + "--" + slugify(sname)
            out.append(f"INSERT INTO categories(parent_id, name, name_hi, slug, sort_order) "
                       f"SELECT id, {q(sname)}, {q(sname_hi)}, {q(sslug)}, {si} FROM categories WHERE slug = {q(cslug)};")
            for (pname, brand, desc, gst, variants) in prods:
                pslug = slugify(pname)
                supplier = 1 if brand == "Gola Fresh" else (3 if brand == "Gola Select" else 2)
                featured = "TRUE" if random.random() < 0.25 else "FALSE"
                out.append(
                    f"INSERT INTO products(name, slug, description, brand_id, category_id, supplier_id, gst_rate, is_featured) "
                    f"SELECT {q(pname)}, {q(pslug)}, {q(desc)}, (SELECT id FROM brands WHERE name = {q(brand)}), c.id, {supplier}, {gst}, {featured} "
                    f"FROM categories c WHERE c.slug = {q(sslug)};")
                for k in (1, 2):
                    out.append(f"INSERT INTO product_images(product_id, url, sort_order) SELECT id, "
                               f"{q(f'/files/catalog/{pslug}-{k}.png')}, {k-1} FROM products WHERE slug = {q(pslug)};")
                for vi, (label, qty, unit, mrp, price) in enumerate(variants):
                    sku_n += 1
                    sku = f"GG-{code}-{sku_n:04d}"
                    out.append(
                        f"INSERT INTO product_variants(product_id, sku, barcode, label, quantity_value, unit, mrp, selling_price, is_default) "
                        f"SELECT id, {q(sku)}, {q(ean13(sku_n))}, {q(label)}, {qty}, {q(unit)}, {mrp}, {price}, {'TRUE' if vi == 0 else 'FALSE'} "
                        f"FROM products WHERE slug = {q(pslug)};")
                    stock = random.choice([0, 4, 8] if random.random() < 0.08 else [25, 40, 60, 80, 120, 150])
                    out.append(f"INSERT INTO inventory(variant_id, quantity, low_stock_threshold) "
                               f"SELECT id, {stock}, 10 FROM product_variants WHERE sku = {q(sku)};")
                if with_images:
                    make_images(pslug, pname, brand, color, variants[0][0])
        out.append("")
    for i, (title, sub, ltype, lval, color) in enumerate(BANNERS):
        bslug = slugify(title)
        out.append(f"INSERT INTO banners(title, subtitle, image_url, link_type, link_value, bg_color, sort_order) VALUES "
                   f"({q(title)}, {q(sub)}, {q('/files/catalog/banner-' + bslug + '.png')}, {q(ltype)}, {q(lval)}, {q(color)}, {i});")
        if with_images:
            make_banner(bslug, title.replace("₹", "Rs."), sub.replace("₹", "Rs."), color)
    for (code, desc, t, val, mx, mn, first) in COUPONS:
        out.append(f"INSERT INTO coupons(code, description, discount_type, discount_value, max_discount, min_order_amount, first_order_only, usage_limit) VALUES "
                   f"({q(code)}, {q(desc)}, {q(t)}, {val}, {mx if mx is not None else 'NULL'}, {mn}, {'TRUE' if first else 'FALSE'}, 10000);")
    for (pin, city, area, fee, eta) in PINCODES:
        out.append(f"INSERT INTO serviceable_pincodes(pincode, city, area, delivery_fee, eta_minutes) VALUES "
                   f"({q(pin)}, {q(city)}, {q(area)}, {fee if fee is not None else 'NULL'}, {eta});")
    with open(OUT_SQL, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"Wrote {OUT_SQL} ({sku_n} variants)")

if __name__ == "__main__":
    main(with_images="--no-images" not in sys.argv)
